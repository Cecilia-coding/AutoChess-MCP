import { readFileSync, writeFileSync } from "node:fs";

// Export the maintained lobby palette; the standalone package ships this snapshot.
const sources = ["components/autochess/theme-revival.css", "components/autochess/room-ui.css"];
const declarations = sources.map((path) => {
  const css = readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
  const root = css.match(/:root[^{}]*\{([^}]+)\}/);
  if (!root) throw new Error(`Theme token block not found: ${path}`);
  return root[1]
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => `  ${line}`)
    .join("\n");
});
const content = `/* Generated by scripts/sync-authoring-theme.mjs from the existing chess lobby. */\n:root {\n${declarations.join("\n")}\n}\n`;
writeFileSync(new URL("../packages/chess-authoring/web/theme.css", import.meta.url), content);
