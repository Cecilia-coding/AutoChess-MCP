export type PixelIconName = keyof typeof masks;
export function PixelIcon({
  name,
  size = 20,
  color,
}: {
  name: PixelIconName;
  size?: number;
  color?: string;
}) {
  return (
    <svg
      className="pixel-icon"
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
      style={{ color } as CSSProperties}
    >
      {masks[name].flatMap((row, y) =>
        [...row].map((cell, x) =>
          cell === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" /> : null,
        ),
      )}
    </svg>
  );
}
