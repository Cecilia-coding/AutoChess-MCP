export const PIXEL_BOARD_SKINS: Readonly<Record<string, PixelBoardSkin>> = Object.fromEntries(
  SKIN_LIST.map(skin => [skin.id, skin]),
);

/** Look up pixel theme tokens for an equipped board skin ID. */
export function pixelBoardSkin(skinId?: string): PixelBoardSkin | undefined {
  return skinId ? PIXEL_BOARD_SKINS[skinId] : undefined;
}

/** Layer an explicitly equipped board skin onto the pack's base pixel appearance without modifying pack sprites. */
export function applyBoardSkinToAppearance(base: PixelAppearance, skinId?: string): PixelAppearance {
  const skin = pixelBoardSkin(skinId);
  if (!skin) return base;
  return {
    ...base,
    boardColors: skin.boardColors,
    boardTheme: skin.boardTheme,
    boardDecor: skin.decor,
  };
}
