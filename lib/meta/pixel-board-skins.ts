import type { PixelAppearance, PixelBoardDecor, PixelBoardMotifKind } from '../presentation/types';

export type PixelBoardSkin = {
  id: string;
  boardColors: PixelAppearance['boardColors'];
  boardTheme: NonNullable<PixelAppearance['boardTheme']>;
  decor: PixelBoardDecor;
};

type SkinSeed = {
  id: string;
  background: string;
  panel: string;
  own: [string, string];
  enemy: [string, string];
  bench: string;
  trim: string;
  text: string;
  plinthDark: string;
  plinthLight: string;
  plinthJoint: string;
  frameDark: string;
  frameInnerLine: string;
  bevelLight: string;
  gridRim: string;
  gridInnerBevel: string;
  ownRim: string;
  enemyRim: string;
  ownPlaque: [string, string, string];
  enemyPlaque: [string, string, string];
  midBar: string;
  midSegments: [string, string];
  midClasp: [string, string, string];
  benchRim: string;
  benchAccents: [string, string];
  benchBar: string;
  shadow: string;
  sparkTrail: string;
  sparkCore: string;
  moteKind: PixelBoardDecor['moteKind'];
  moteColors: readonly [string, string, string];
  cornerMotif: PixelBoardMotifKind;
  scene?: string;
};

function defineSkin(s: SkinSeed): PixelBoardSkin {
  return {
    id: s.id,
    boardColors: {
      background: s.background,
      panel: s.panel,
      own: s.own,
      enemy: s.enemy,
      bench: s.bench,
      trim: s.trim,
      text: s.text,
    },
    boardTheme: {
      plinthShadow: `${s.shadow}2a`,
      plinthDark: s.plinthDark,
      plinthLight: s.plinthLight,
      plinthJoint: s.plinthJoint,
      frameDark: s.frameDark,
      frameInnerLine: s.frameInnerLine,
      bevelLight: s.bevelLight,
      gridRim: s.gridRim,
      gridInnerBevel: s.gridInnerBevel,
      ownRim: s.ownRim,
      enemyRim: s.enemyRim,
      ownPlaque: s.ownPlaque,
      enemyPlaque: s.enemyPlaque,
      midBar: s.midBar,
      midSegments: s.midSegments,
      midClasp: s.midClasp,
      benchRim: s.benchRim,
      benchAccents: s.benchAccents,
      benchBar: s.benchBar,
      shadow: s.shadow,
      sparkTrail: s.sparkTrail,
      sparkCore: s.sparkCore,
    },
    decor: {
      moteKind: s.moteKind,
      moteColors: s.moteColors,
      cornerMotif: s.cornerMotif,
      ...(s.scene ? { scene: s.scene } : {}),
    },
  };
}

